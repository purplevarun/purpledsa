// One-off script: extracts the TOPICS data embedded in NC_150.html and generates
// src/data/neetcode150.ts with LeetCode/NeetCode URLs resolved, matching the
// original page's lcSlug/lcUrl logic exactly.
import fs from "node:fs";
import path from "node:path";

const SRC_HTML = path.resolve("../NC_150.html");
const OUT_FILE = path.resolve("src/data/neetcode150.ts");

const html = fs.readFileSync(SRC_HTML, "utf8");
const start = html.indexOf("var TOPICS = [");
const end = html.indexOf("\n  ];", start) + "\n  ];".length;
if (start === -1 || end === -1) throw new Error("Could not locate TOPICS array in NC_150.html");
const arrayLiteral = html.slice(start + "var TOPICS = ".length, end - 1);

const TOPICS = new Function(`return (${arrayLiteral});`)();

function lcSlug(name) {
  const overrides = { "Pow(x, n)": "powx-n" };
  if (overrides[name]) return overrides[name];
  return name.toLowerCase().replace(/'/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}
function lcUrl(name) {
  const alt = {
    "Encode and Decode Strings": "https://neetcode.io/problems/string-encode-and-decode",
    "Walls and Gates": "https://neetcode.io/problems/islands-and-treasure",
    "Alien Dictionary": "https://neetcode.io/problems/foreign-dictionary",
    "Meeting Rooms": "https://neetcode.io/problems/meeting-schedule",
    "Meeting Rooms II": "https://neetcode.io/problems/meeting-schedule-ii",
  };
  return alt[name] || `https://leetcode.com/problems/${lcSlug(name)}/`;
}

let order = 0;
const topics = TOPICS.map((topic) => ({
  name: topic.name.replace(/&amp;/g, "&"),
  problems: topic.items.map((it) => {
    order += 1;
    return {
      order,
      slug: lcSlug(it.n),
      name: it.n,
      difficulty: it.d,
      url: lcUrl(it.n),
      locked: !!it.lock,
      hints: it.h,
    };
  }),
}));

const banner = `// AUTO-GENERATED by scripts/extract-neetcode150.mjs from NC_150.html. Do not edit by hand.\n`;
const body = `${banner}import type { ProblemTopic } from "@/types/problems";\n\nexport const neetcode150: ProblemTopic[] = ${JSON.stringify(topics, null, 2)};\n`;
fs.writeFileSync(OUT_FILE, body);
console.log(`Wrote ${OUT_FILE} with ${topics.length} topics, ${order} problems.`);
